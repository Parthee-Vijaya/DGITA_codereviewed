  expect((await page.request.post("/api/auth/dev-login", { headers, data: { role: "user" } })).status()).toBe(200);
  const draft: ApplicationFormState = { ...structuredClone(demoApplicationState), knownSystem: "nej", selectedSystem: null, manualSystemName: "Syntetisk uafklaret anskaffelse", consent: true, contractCoverage: "existing-agreement", agreementReference: "Journal 123" };
  const saved = await (await page.request.post("/api/drafts", { headers, data: { id: crypto.randomUUID(), draft, status: "draft" } })).json();
  const readDraft = async () => (await (await page.request.get(`/api/drafts?caseNumber=${saved.caseNumber}`)).json()).draft.state;
  await page.goto(`/?view=application&draft=${saved.caseNumber}`);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Investering", exact: true }).click();
  const valueStatus = page.getByRole("radiogroup", { name: "Er den samlede kontraktværdi anslået?", exact: true });
  const coverage = page.getByRole("radiogroup", { name: "Hvordan dækkes anskaffelsen af en aftale?", exact: true });
  await valueStatus.getByRole("radio", { name: "Skal afklares", exact: true }).click();
  await coverage.getByRole("radio", { name: "Skal afklares", exact: true }).click();
  await expect(page.getByRole("textbox", { name: estimateLabel, exact: true })).toHaveCount(0);
  await expect(page.getByRole("textbox", { name: referenceLabel, exact: true })).toHaveCount(0);
  await expect(page.getByText(/Afklar kontraktværdi og aftaleform med kommunens indkøbsansvarlige/)).toBeVisible();
